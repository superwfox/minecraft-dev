import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://fill.papermc.io/v3/projects/paper";
const TARGET_FILE = resolve(dirname(fileURLToPath(import.meta.url)), "../src/logic/minecraftVersions.ts");
const STABLE_VERSION = /^\d+(?:\.\d+)*$/;
const MIN_EXPECTED_FAMILIES = 10;

function compareVersionsDescending(left, right) {
    const leftParts = left.split(".").map(Number);
    const rightParts = right.split(".").map(Number);
    const length = Math.max(leftParts.length, rightParts.length);

    for (let index = 0; index < length; index++) {
        const difference = (rightParts[index] ?? 0) - (leftParts[index] ?? 0);
        if (difference !== 0) return difference;
    }
    return 0;
}

function stableFamilies(payload) {
    if (!payload || typeof payload !== "object" || !payload.versions || typeof payload.versions !== "object") {
        throw new Error("PaperMC response does not contain a versions object");
    }

    const families = Object.entries(payload.versions)
        .filter(([family, releases]) => (
            STABLE_VERSION.test(family)
            && Array.isArray(releases)
            && releases.some((release) => typeof release === "string" && STABLE_VERSION.test(release))
        ))
        .map(([family]) => family)
        .sort(compareVersionsDescending);

    if (families.length < MIN_EXPECTED_FAMILIES) {
        throw new Error(`PaperMC returned only ${families.length} stable version families`);
    }
    return families;
}

function renderVersionModule(versions) {
    const entries = versions.map((version) => `    "${version}",`).join("\n");
    return `// Generated by npm run versions:update from PaperMC Fill v3.\n`
        + `export const MINECRAFT_VERSIONS = [\n${entries}\n] as const;\n\n`
        + `export const MINECRAFT_VERSION_ENUM = [...MINECRAFT_VERSIONS, "null"]\n`
        + `    .map((version) => \`"\${version}"\`)\n`
        + `    .join(",");\n`;
}

const response = await fetch(SOURCE_URL, {
    headers: {
        Accept: "application/json",
        "User-Agent": "minecraft-dev-version-updater",
    },
    signal: AbortSignal.timeout(20_000),
});

if (!response.ok) {
    throw new Error(`PaperMC request failed with HTTP ${response.status}`);
}

const nextContent = renderVersionModule(stableFamilies(await response.json()));
const currentContent = await readFile(TARGET_FILE, "utf8").catch(() => "");

if (currentContent === nextContent) {
    console.log("Minecraft version list is already current.");
} else {
    await writeFile(TARGET_FILE, nextContent, "utf8");
    console.log(`Updated ${TARGET_FILE}`);
}
